import mongoose, { Schema } from "mongoose"

const linkSchema = new Schema({
  productId: { type: Schema.Types.ObjectId, ref: "Product", required: true },
  priceAmount: { type: Number, default: null, min: 0 },
  currency: { type: String, enum: ["", "BRL", "USD", "EUR", "CNY"], default: "" },
  unitPrice: { type: String, default: "" },
  moq: { type: String, default: "" },
  deliveryTime: { type: String, default: "" },
  paymentTerms: { type: String, default: "" },
  domesticFreight: { type: String, default: "" },
  originCountry: { type: String, default: "" },
  incoterm: { type: String, default: "" },
  transportMode: { type: String, default: "" },
  sample: { type: String, enum: ["unknown", "yes", "no"], default: "unknown" },
  notes: { type: String, default: "" },
}, { _id: false })

const schema = new Schema({
  links: { type: [linkSchema], default: undefined },
  name: { type: String, required: true, trim: true, maxlength: 200 },
  individuallyAnalyzed: { type: Boolean, default: false },
  supplierType: { type: String, default: "" },
  rating: { type: Number, default: 0 },
  tradeAssurance: { type: Boolean, default: false },
  yearsInBusiness: { type: Number, default: 0 },
  responseRate: { type: String, default: "" },
  capabilities: { type: String, default: "" },
  certifications: { type: String, default: "" },
  report: { type: String, default: "" },
  contact: { type: String, default: "" },
  email: { type: String, default: "" },
  phone: { type: String, default: "" },
  country: { type: String, default: "" },
  url: { type: String, default: "" },
  status: { type: String, enum: ["prospect", "negotiating", "approved", "inactive"], default: "prospect" },
  purchaseOrigin: { type: String, enum: ["unknown", "domestic", "import"], default: "unknown" },
  priceAmount: { type: Number, default: null, min: 0 },
  currency: { type: String, enum: ["", "BRL", "USD", "EUR", "CNY"], default: "" },
  legalName: { type: String, default: "" },
  taxId: { type: String, default: "" },
  state: { type: String, default: "" },
  city: { type: String, default: "" },
  invoice: { type: String, enum: ["unknown", "yes", "no"], default: "unknown" },
  domesticFreight: { type: String, default: "" },
  originCountry: { type: String, default: "" },
  contactChannel: { type: String, default: "" },
  incoterm: { type: String, default: "" },
  transportMode: { type: String, default: "" },
  sample: { type: String, enum: ["unknown", "yes", "no"], default: "unknown" },
  unitPrice: { type: String, default: "" },
  moq: { type: String, default: "" },
  deliveryTime: { type: String, default: "" },
  paymentTerms: { type: String, default: "" },
  notes: { type: String, default: "" },
  productId: { type: Schema.Types.ObjectId, ref: "Product", default: null },
}, { timestamps: true })
schema.index({ "links.productId": 1 })
export const SupplierRecord = mongoose.model("SupplierRecord", schema)
